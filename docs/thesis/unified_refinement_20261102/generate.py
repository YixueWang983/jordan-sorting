"""Derive the requested manuscript additions from saved records; no sorting."""
import gzip
import hashlib
import json
from pathlib import Path
import statistics as st

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
ARCHIVE = ROOT / "docs/validation/unified_formal_20261101"
ANALYSIS = ARCHIVE / "unified_analysis_bca4c1c6_restart_20261101_01"
FORMAL = ARCHIVE / "unified_formal_bca4c1c6_restart_20261101_01"
INPUTS = {}


def read(path):
    data = path.read_bytes()
    INPUTS[str(path.relative_to(ROOT))] = hashlib.sha256(data).hexdigest()
    return json.loads(gzip.decompress(data) if path.suffix == ".gz" else data)


def main():
    cases = read(ANALYSIS / "cases.json")
    ctor = read(ROOT / "docs/validation/unified_followup_20261101/results/analysis/constructor_summary.json")
    previous = read(ROOT / "docs/thesis/unified_results_20261101/derived.json")
    endpoints = {}
    for source in dict.fromkeys(c["source"] for c in cases):
        rows = [c for c in cases if c["source"] == source]
        ns = sorted({c["n"] for c in rows})
        points = [dict(n=n, inputs=sum(c["n"] == n for c in rows),
                       median=st.median(c["ratio"] for c in rows if c["n"] == n)) for n in ns]
        endpoints[source] = dict(by_length=points, smallest=points[0], largest=points[-1],
                                 largest_lower_than_smallest=points[-1]["median"] < points[0]["median"])
    assert all(x["largest_lower_than_smallest"] for x in endpoints.values())
    bands = {}
    for label, ns in [("32/33", [32, 33]), ("512/513", [512, 513])]:
        median = st.median(c["ratio"] for c in cases if c["n"] in ns)
        assert median == previous["size_bins"][label]["median"]
        bands[label] = median
    backend = "heterogeneous_finger_uninstrumented"
    shortest = min(cases, key=lambda c: c["groups"][backend]["median_ns_per_call"])
    shortest_ns = shortest["groups"][backend]["median_ns_per_call"]
    records = [read(p) for p in sorted((FORMAL / "sources" / shortest["source"] /
               "jobs" / shortest["case_id"] / "records").glob("*.json.gz"))]
    samples = [r for r in records if r["kind"] == "sample" and r["backend"] == backend]
    assert len(samples) == 20
    assert st.median(r["elapsed_ns"] / r["batch_size"] for r in samples) == shortest_ns
    difference_ns = ctor["paired_difference_ns"]["median"]
    percent = 100 * difference_ns / shortest_ns
    families = len(endpoints)
    macros = dict(UnifiedMinN=min(c["n"] for c in cases),
                  UnifiedFamilyCount={5: "five"}[families],
                  UnifiedSmallBand="32/33", UnifiedLargeBand="512/513",
                  UnifiedSmallBandMedian=f"{bands['32/33']:.3f}",
                  UnifiedLargeBandMedian=f"{bands['512/513']:.3f}",
                  UnifiedShortestTreeUs=f"{shortest_ns / 1000:.3f}",
                  UnifiedCtorShortestPercent=f"{percent:.2f}")
    (ROOT / "thesis/generated/unified_refinement.tex").write_text(
        "% Generated by docs/thesis/unified_refinement_20261102/generate.py\n" +
        "".join(f"\\newcommand{{\\{key}}}{{{value}}}\n" for key, value in macros.items()))
    facts = dict(source_endpoints=endpoints, abstract_band_medians=bands, macros=macros,
                 constructor_comparison=dict(shortest_tree_case=shortest["case_id"],
                 shortest_tree_median_ns=shortest_ns, paired_constructor_difference_ns=difference_ns,
                 percent_of_shortest_tree_median=percent,
                 formula="100 * paired_difference_ns.median / min(tree_median_ns_per_call)",
                 interpretation="Scale comparison across two measurement designs, not an isolated binding-cost estimate."))
    (HERE / "derived.json").write_text(json.dumps(facts, indent=2) + "\n")
    (HERE / "provenance.json").write_text(json.dumps(dict(inputs=INPUTS,
        script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        new_measurements_executed=False), indent=2) + "\n")
    print(json.dumps(dict(endpoints={k: v['largest_lower_than_smallest'] for k,v in endpoints.items()},
                         constructor_percent=percent, macros=macros), indent=2))


if __name__ == "__main__":
    main()
